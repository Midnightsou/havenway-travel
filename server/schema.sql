-- Havenway Travel Admin Schema
-- Run this SQL in your Supabase SQL editor to create the admin tables.

-- Flights (stores flight plans: economy, business, first)
CREATE TABLE IF NOT EXISTS admin_flights (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  plan_key TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  data JSONB NOT NULL DEFAULT '{}',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Hotels
CREATE TABLE IF NOT EXISTS admin_hotels (
  id TEXT PRIMARY KEY DEFAULT gen_random_uuid()::TEXT,
  name TEXT NOT NULL,
  location TEXT NOT NULL,
  rating NUMERIC(2,1),
  rating_label TEXT,
  review_count INTEGER DEFAULT 0,
  description TEXT,
  long_description TEXT,
  check_in TEXT,
  check_out TEXT,
  amenities JSONB DEFAULT '[]',
  highlights JSONB DEFAULT '[]',
  images JSONB DEFAULT '[]',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Rooms (linked to a hotel)
CREATE TABLE IF NOT EXISTS admin_rooms (
  id TEXT PRIMARY KEY DEFAULT gen_random_uuid()::TEXT,
  hotel_id TEXT NOT NULL,
  name TEXT NOT NULL,
  beds TEXT,
  guests TEXT,
  price_per_night INTEGER DEFAULT 0,
  amenities JSONB DEFAULT '[]',
  images JSONB DEFAULT '[]',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Cars
CREATE TABLE IF NOT EXISTS admin_cars (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL,
  name TEXT NOT NULL,
  price_per_day INTEGER DEFAULT 0,
  seats INTEGER DEFAULT 0,
  bags INTEGER DEFAULT 0,
  transmission TEXT,
  features JSONB DEFAULT '[]',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Activities
CREATE TABLE IF NOT EXISTS admin_activities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  location TEXT,
  duration TEXT,
  price_per_person INTEGER DEFAULT 0,
  rating NUMERIC(2,1),
  reviews INTEGER DEFAULT 0,
  description TEXT,
  includes JSONB DEFAULT '[]',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Packages
CREATE TABLE IF NOT EXISTS admin_packages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  type TEXT,
  description TEXT,
  room_id TEXT,
  discount NUMERIC(3,2) DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Keep IDs compatible with the existing site catalog while allowing the
-- admin API to generate IDs for items created from the dashboard.
ALTER TABLE admin_hotels
  ALTER COLUMN id DROP DEFAULT,
  ALTER COLUMN id TYPE TEXT USING id::TEXT,
  ALTER COLUMN id SET DEFAULT gen_random_uuid()::TEXT;

ALTER TABLE admin_rooms
  ALTER COLUMN id DROP DEFAULT,
  ALTER COLUMN id TYPE TEXT USING id::TEXT,
  ALTER COLUMN id SET DEFAULT gen_random_uuid()::TEXT;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = current_schema()
      AND table_name = 'admin_cars'
      AND column_name = 'id'
      AND is_identity = 'YES'
  ) THEN
    ALTER TABLE admin_cars ALTER COLUMN id DROP DEFAULT;
    ALTER TABLE admin_cars ALTER COLUMN id TYPE BIGINT USING id::BIGINT;
    ALTER TABLE admin_cars ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = current_schema()
      AND table_name = 'admin_activities'
      AND column_name = 'id'
      AND is_identity = 'YES'
  ) THEN
    ALTER TABLE admin_activities ALTER COLUMN id DROP DEFAULT;
    ALTER TABLE admin_activities ALTER COLUMN id TYPE BIGINT USING id::BIGINT;
    ALTER TABLE admin_activities ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = current_schema()
      AND table_name = 'admin_packages'
      AND column_name = 'id'
      AND is_identity = 'YES'
  ) THEN
    ALTER TABLE admin_packages ALTER COLUMN id DROP DEFAULT;
    ALTER TABLE admin_packages ALTER COLUMN id TYPE BIGINT USING id::BIGINT;
    ALTER TABLE admin_packages ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END $$;

SELECT setval(pg_get_serial_sequence('admin_cars', 'id'), COALESCE(MAX(id), 0) + 1, FALSE)
FROM admin_cars;
SELECT setval(pg_get_serial_sequence('admin_activities', 'id'), COALESCE(MAX(id), 0) + 1, FALSE)
FROM admin_activities;
SELECT setval(pg_get_serial_sequence('admin_packages', 'id'), COALESCE(MAX(id), 0) + 1, FALSE)
FROM admin_packages;

CREATE OR REPLACE FUNCTION sync_admin_catalog_sequences()
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  PERFORM setval(
    pg_get_serial_sequence('public.admin_cars', 'id'),
    COALESCE((SELECT MAX(id) FROM public.admin_cars), 0) + 1,
    FALSE
  );
  PERFORM setval(
    pg_get_serial_sequence('public.admin_activities', 'id'),
    COALESCE((SELECT MAX(id) FROM public.admin_activities), 0) + 1,
    FALSE
  );
  PERFORM setval(
    pg_get_serial_sequence('public.admin_packages', 'id'),
    COALESCE((SELECT MAX(id) FROM public.admin_packages), 0) + 1,
    FALSE
  );
END;
$$;

REVOKE ALL ON FUNCTION sync_admin_catalog_sequences() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION sync_admin_catalog_sequences() TO service_role;

CREATE TABLE IF NOT EXISTS admin_settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE admin_settings ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE admin_settings FROM anon, authenticated;
GRANT ALL ON TABLE admin_settings TO service_role;

INSERT INTO storage.buckets (
  id,
  name,
  public,
  file_size_limit,
  allowed_mime_types
)
VALUES (
  'catalog-images',
  'catalog-images',
  TRUE,
  7340032,
  ARRAY['image/jpeg', 'image/png', 'image/webp', 'image/gif']
)
ON CONFLICT (id) DO UPDATE
SET public = EXCLUDED.public,
    file_size_limit = EXCLUDED.file_size_limit,
    allowed_mime_types = EXCLUDED.allowed_mime_types;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'storage'
      AND tablename = 'objects'
      AND policyname = 'catalog_images_public_read'
  ) THEN
    CREATE POLICY catalog_images_public_read
      ON storage.objects
      FOR SELECT
      TO anon, authenticated
      USING (bucket_id = 'catalog-images');
  END IF;
END $$;

